"""The committed conformance workflow, rendered from the contract (ADR-project-contract-015).

Resolve-project projects the `conformance_workflow` kind through `render`: a pure function of the
integration branch, the schema version and the form. The platform's own tree runs the platform
from the tree itself, with `--lint-times`; every other tree runs it from the revision its
`devenv.lock` pins as `agent-platform` (ADR-project-contract-018), without it.

The own-tree form also builds the platform at the pull request's base (on a push, the previous
tip) and reads the head's contract with it: the job fails when that platform refuses the
contract or finds it incompatible, and annotates each binding it ignores as a warning.
"""

from __future__ import annotations

import os
from pathlib import Path
import re

from agent_tools.project_contract import derived_values

# A branch the rendered workflow may carry as a double-quoted YAML string: no
# quote, backslash, space or control character can reach it.
WORKFLOW_BRANCH_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._/-]*$")

# The rendered form, a wire format: only {version}, {branch} and {run} vary; one final
# newline. The head is shared; the run step is the platform's own tree's or the locked form's.
WORKFLOW_TEMPLATE = """\
# Generated by resolve-project (project schema {version}). Do not edit: the
# Conformance check fails while this file differs from what resolve-project renders.
name: Conformance

on:
  pull_request:
    branches:
      - "{branch}"
  push:
    branches:
      - "{branch}"

permissions:
  contents: read

jobs:
  conformance:
    name: Conformance
    runs-on: ubuntu-24.04
    timeout-minutes: 30
    steps:
      - name: Checkout
        uses: actions/checkout@v4
        with:
          fetch-depth: 0
          ref: ${{{{ github.event.pull_request.head.sha || github.sha }}}}
      - name: Install Nix
        uses: DeterminateSystems/nix-installer-action@v4
      - name: Run conformance
{run}"""
RUN_OWN_TREE = (
    "        run: nix shell .#agent-platform --command conformance run --purpose ci --lint-times\n"
    "      - name: Read the contract with the base platform\n"
    "        run: |\n"
    "          base=\"git+file://$GITHUB_WORKSPACE?rev=${{ github.event.pull_request.base.sha || github.event.before }}\"\n"
    "          nix build \"$base#agent-platform\" --out-link \"$RUNNER_TEMP/base-platform\"\n"
    "          \"$RUNNER_TEMP/base-platform/bin/resolve-project\" platform-status --repo-root . "
    ">\"$RUNNER_TEMP/base-status.json\" 2>\"$RUNNER_TEMP/base-warnings.txt\" "
    "|| { cat \"$RUNNER_TEMP/base-status.json\"; exit 1; }\n"
    "          sed 's/^/::warning::/' \"$RUNNER_TEMP/base-warnings.txt\"\n"
    "          jq -e '.compatibility.compatible' \"$RUNNER_TEMP/base-status.json\"\n")
# A single backslash before each `(` is inside the YAML block scalar, where jq
# reads it as string interpolation.
RUN_LOCKED = (
    "        run: |\n"
    "          platform=$(jq -er '.nodes[.nodes[.root].inputs[\"agent-platform\"]]"
    ".locked | select(.type == \"github\") | "
    "\"github:\\(.owner)/\\(.repo)/\\(.rev)\"' devenv.lock)\n"
    "          nix shell \"$platform#agent-platform\" "
    "--command conformance run --purpose ci\n")


def locked(root: Path) -> bool:
    """Contract: whether `root` gets the locked form of the conformance workflow.

    The platform's own tree is the one holding `derived_values.TREE_MANIFEST`
    (even as a dangling symlink); every other tree is locked.
    """
    return not os.path.lexists(root / derived_values.TREE_MANIFEST)


def render(integration_branch: str, schema_version: int,
                                *, locked: bool) -> bytes:
    """Contract: the exact bytes of the committed conformance workflow.

    A pure function of its three arguments: `locked=False` runs the platform
    from the tree itself, `locked=True` from the revision `devenv.lock` pins as
    `agent-platform`; no revision or repository literal reaches either form. The branch is
    written as a double-quoted YAML string, so `null`, `true` or `123` stays a string; a
    branch outside `WORKFLOW_BRANCH_PATTERN` is a `ValueError`.
    """
    if WORKFLOW_BRANCH_PATTERN.fullmatch(integration_branch) is None:
        raise ValueError(f"integration branch is not workflow-safe: {integration_branch!r}")
    return WORKFLOW_TEMPLATE.format(
        version=schema_version, branch=integration_branch,
        run=RUN_LOCKED if locked else RUN_OWN_TREE,
    ).encode("utf-8")
