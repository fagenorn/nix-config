def post_page(address, path, headers=None, body=b"", host=None):
    """A POST that sends exactly the headers given, plus Host and Content-Length.

    A header's value may be a list: the header is then sent once per member.
    """
    connection = http.client.HTTPConnection(*address, timeout=5)
    try:
        connection.putrequest("POST", path, skip_host=True)
        connection.putheader("Host", f"{address[0]}:{address[1]}" if host is None else host)
        for name, value in (headers or {}).items():
            for each in value if isinstance(value, list) else [value]:
                connection.putheader(name, each)
        connection.putheader("Content-Length", str(len(body)))
        connection.endheaders(body)
        response = connection.getresponse()
        return response.status, dict(response.getheaders()), response.read()
    finally:
        connection.close()


def write_session(directory, *, pid, session_id, cwd, status, waiting_for=None, name=None,
                  updated_at=None):
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    document = {"pid": pid, "sessionId": session_id, "cwd": cwd, "status": status,
                "updatedAt": int(time.time() * 1000) if updated_at is None else updated_at}
    stat = Path("/proc") / str(pid) / "stat"
    if stat.exists():
        document["procStart"] = stat.read_text().rsplit(")", 1)[1].split()[19]
        document["pidDomain"] = console_sessions.own_pid_domain()
    if waiting_for is not None:
        document["waitingFor"] = waiting_for
    if name is not None:
        document["name"] = name
    handle, temporary = tempfile.mkstemp(dir=directory)
    with os.fdopen(handle, "w") as stream:
        json.dump(document, stream)
    os.replace(temporary, directory / f"{pid}.json")


HOOK_FIXTURE = Path(__file__).parent / "fixtures" / "console" / "hook-payloads.json"


def hook_cases():
    document = json.loads(HOOK_FIXTURE.read_text())
    return [(case["name"], {**document["common"], **case["payload"]}, case["expect"])
            for case in document["cases"]]


def hook_body(name, **overrides):
    for case_name, payload, _ in hook_cases():
        if case_name == name:
            return json.dumps({**payload, **overrides}).encode("utf-8")
    raise KeyError(name)


class Launches:
    """A `launcher` stand-in: records each launch; `fail` is consumed per call (a str is a failure)."""

    def __init__(self, fail=None):
        self.calls = []
        self.fail = list(fail or [])

    def __call__(self, launch):
        self.calls.append(launch)
        reason = self.fail.pop(0) if self.fail else None
        if reason is not None:
            raise console_manager.LaunchFailed(reason)


def goal_of(prompt: str) -> str:
    """The goal of a launch prompt: the text after the first `The goal: ` not on a `- ` line."""
    offset = 0
    for line in prompt.splitlines(keepends=True):
        if not line.startswith("- ") and "The goal: " in line:
            return prompt[offset + line.index("The goal: ") + len("The goal: "):]
        offset += len(line)
    raise AssertionError("no goal in the prompt")


class Queued:
    """A `dispatch` stand-in: holds each job until `run_next` runs the oldest."""

    def __init__(self):
        self.jobs = []

    def __call__(self, job):
        self.jobs.append(job)

    def run_next(self):
        self.jobs.pop(0)()


