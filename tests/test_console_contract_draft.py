def git(path, *arguments):
    done = subprocess.run(
        ["git", "-C", str(path), *arguments], env=GIT_ENV, check=True, text=True,
        stdin=subprocess.DEVNULL, stdout=subprocess.PIPE)
    return done.stdout


def commit(root: Path, files: dict[str, str]) -> None:
    for name, text in files.items():
        (root / name).write_text(text)
    git(root, "add", "-A")
    git(root, "commit", "-q", "-m", "more")


def sample(parent: Path, *, remote: bool, name: str = "sample-app") -> Path:
    root = parent / name
    root.mkdir(parents=True)
    git(root, "init", "-q", "-b", "trunk")
    git(root, "config", "user.name", "t")
    git(root, "config", "user.email", "t@example.invalid")
    git(root, "config", "commit.gpgsign", "false")
    (root / "README.md").write_text("# x\n")
    git(root, "add", "-A")
    git(root, "commit", "-q", "-m", "one")
    if remote:
        bare = parent / "origin.git"
        git(parent, "clone", "-q", "--bare", str(root), str(bare))
        git(root, "remote", "add", "origin", "https://github.com/sample-owner/sample-app.git")
        git(root, "config", f"url.{bare}.insteadOf", "https://github.com/sample-owner/sample-app.git")
    return root


def install_hook(root, name="pre-commit", text="#!/bin/sh\nexit 0\n", mode=0o755):
    hooks = Path(git(root, "rev-parse", "--path-format=absolute", "--git-common-dir").strip()) / "hooks"
    hooks.mkdir(exist_ok=True)
    (hooks / name).write_text(text)
    (hooks / name).chmod(mode)


def by_field(fields):
    return {f["field"]: f for f in fields}


def pair(fields, field):
    record = by_field(fields)[field]
    return record["value"], record["source"]


class ContractDraftTest(unittest.TestCase):
    def setUp(self):
        self.parent = Path(tempfile.mkdtemp()).resolve()
        self.addCleanup(shutil.rmtree, self.parent, ignore_errors=True)
        self.saved = os.environ.get("GIT_ALLOW_PROTOCOL")
        os.environ["GIT_ALLOW_PROTOCOL"] = "file"
        self.addCleanup(self.restore)

    def restore(self):
        if self.saved is None:
            os.environ.pop("GIT_ALLOW_PROTOCOL", None)
        else:
            os.environ["GIT_ALLOW_PROTOCOL"] = self.saved

    def remote_fields(self):
        root = str(sample(self.parent, remote=True))
        return root, cd.draft(root, cd.read(root))

    def settled(self, fields, root, **values):
        for field, value in values.items():
            fields, error = cd.set_value(fields, field.replace("_", "-"), value)
            self.assertIsNone(error)
        return fields

    def test_the_draft_asks_nothing_about_co_author_lines(self):
        root, fields = self.remote_fields()
        for table in (cd.FIELDS, cd.LABELS, cd.POINTERS, cd.OPTIONS, cd.TEXT, cd.STARTS, cd.REST_WORDS):
            self.assertNotIn("co-authored-by", table)
        self.assertNotIn("co-authored-by", [f["field"] for f in fields])
        self.assertNotIn("co-authored-by", [q["subject"] for q in cd.questions(fields)])
        shown = cd.shown(fields)
        words = [e["line"] for e in shown] + [o["label"] for e in shown for o in e["options"]]
        words.append(cd.more_line(fields))
        for word in words:
            self.assertNotIn("co-author", word.lower())
        self.assertEqual(cd.set_value(fields, "co-authored-by", "yes"), (None, cd.UNKNOWN_FIELD))

    def test_a_saved_draft_with_a_co_author_record_reads_back_without_it(self):
        root, fields = self.remote_fields()
        saved = list(fields)
        record = {"field": "co-authored-by", "label": "co-author lines in commits", "value": "yes",
                  "source": "owner",
                  "options": [{"value": "yes", "label": "yes"}, {"value": "no", "label": "no"}],
                  "text": False, "reason": None, "ask": "Should its commits carry co-author lines?"}
        self.assertEqual(set(record), set(cd.FIELD_KEYS))
        saved.insert(8, record)
        refreshed = cd.refresh(root, saved)
        self.assertEqual([f["field"] for f in refreshed], [*cd.FIELDS, *cd.FACTS])
        self.assertNotIn("co-authored-by", [e["field"] for e in cd.shown(refreshed)])
        settled = self.settled(refreshed, root, lint_command="just lint", test_command="just test")
        self.assertNotIn("commit", cd.contract(settled)["bindings"]["vcs"])
        self.assertEqual(cd.set_value(refreshed, "co-authored-by", "no"), (None, cd.UNKNOWN_FIELD))

    def test_a_github_remote_is_read_for_the_integration_branch_and_the_facts(self):
        root, fields = self.remote_fields()
